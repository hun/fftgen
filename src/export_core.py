def engine_cfg(cfg: FFTConfig) -> FFTConfig:
    """The config whose per-stage schedule feeds the RTL generics: the
    M-point lane engine for SSR, the transform itself for R=1."""
    return lane_cfg(cfg) if cfg.ssr > 1 else cfg


