        "    output wire                        m_axis_tuser,",
        "    output wire                        m_axis_tlast,",
        f"    output wire [NUM_POINTS*INTERN_WIDTH-1:0] dbg_stage_re,",
        f"    output wire [NUM_POINTS*INTERN_WIDTH-1:0] dbg_stage_im,",
